import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterEach, describe, expect, it, vi } from "vitest";
import {
  setBotPrivateInPushStore,
  updateClientPushPresence,
  recordBotPushSent,
} from "./push.js";
import {
  extractGroupEventNotification,
  formatPushPreview,
  isNonNotifiableAssistantMessage,
  startHermesPushWatcher,
  type WatchedDbMessageRow,
} from "./pushWatcher.js";

describe("pushWatcher", () => {
  const tempDirs: string[] = [];

  afterEach(() => {
    updateClientPushPresence(false);
    for (const dir of tempDirs.splice(0)) {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

  it("formats push previews cleanly including image-only MEDIA replies", () => {
    expect(formatPushPreview("MEDIA:/tmp/cat.png")).toBe("Neues Bild gesendet");
    expect(
      formatPushPreview("**Fertig!** Schau dir das Bild an.\nMEDIA:/tmp/cat.png")
    ).toBe("Fertig! Schau dir das Bild an.");
    expect(formatPushPreview("[POCKET_PAGE: id=1 | title=Briefing]")).toBe(
      "Neues Briefing erstellt"
    );
    expect(
      extractGroupEventNotification({
        rowid: 1,
        room_id: "room-team",
        room_name: "Team",
        kind: "message",
        actor_json: JSON.stringify({ kind: "bot", display_name: "Mia" }),
        payload_json: JSON.stringify({ text: "Deal gefunden!" }),
      })
    ).toEqual({
      roomId: "room-team",
      roomName: "Team",
      senderLabel: "Mia",
      preview: "Deal gefunden!",
    });
    expect(
      extractGroupEventNotification({
        rowid: 2,
        room_id: "room-team",
        room_name: "Team",
        kind: "message",
        actor_json: JSON.stringify({ kind: "user", name: "Alex" }),
        payload_json: JSON.stringify({ text: "Hallo zusammen" }),
      })
    ).toBeNull();
  });

  it("filters out subagent, silent, reaction-only, and internal gateway messages", () => {
    expect(
      isNonNotifiableAssistantMessage({
        id: 1,
        role: "assistant",
        content: "Subagent work",
        session_source: "subagent",
      })
    ).toBe(true);
    expect(
      isNonNotifiableAssistantMessage({
        id: 2,
        role: "assistant",
        content: "[SILENT]",
      })
    ).toBe(true);
    expect(
      isNonNotifiableAssistantMessage({
        id: 3,
        role: "assistant",
        content: "[REACT: 👍]",
      })
    ).toBe(true);
    expect(
      isNonNotifiableAssistantMessage({
        id: 4,
        role: "assistant",
        content:
          "[ASYNC DELEGATION COMPLETE — deleg_123]\n[INTERNAL NOTIFICATION — generated by the Hermes gateway]",
      })
    ).toBe(true);
    expect(
      isNonNotifiableAssistantMessage({
        id: 5,
        role: "assistant",
        content: "Mia, ich habe keine Maße gefunden.",
        session_source: "local",
        prev_user_content: "Message from 🤖 Mia (@mia-einkauf): Hallo Nina, kannst du nach Maßen suchen?",
      })
    ).toBe(true);
    expect(
      isNonNotifiableAssistantMessage({
        id: 6,
        role: "assistant",
        content: "Dein Bild ist fertig!",
        session_source: "gui",
      })
    ).toBe(false);
  });

  it("seeds baseline without spamming and dispatches push when a bot finishes while backgrounded", async () => {
    const tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), "hp-watcher-test-"));
    tempDirs.push(tmpRoot);

    const pushDataDir = path.join(tmpRoot, "push-data");
    fs.mkdirSync(pushDataDir, { recursive: true });
    fs.writeFileSync(
      path.join(pushDataDir, "push-store.json"),
      JSON.stringify({
        vapidPublicKey: "pub",
        vapidPrivateKey: "priv",
        botPushToken: "tok",
        subscriptions: [
          {
            endpoint: "https://web.push.apple.com/test",
            keys: { p256dh: "k1", auth: "k2" },
            createdAt: Date.now(),
          },
        ],
        preferences: { globalEnabled: true, disabledBots: [] },
        privateBots: [],
      })
    );
    process.env.PUSH_DATA_DIR = pushDataDir;

    const hermesHome = path.join(tmpRoot, "hermes");
    const annaDir = path.join(hermesHome, "profiles", "anna-coding");
    const emmaDir = path.join(hermesHome, "profiles", "emma");
    fs.mkdirSync(annaDir, { recursive: true });
    fs.mkdirSync(emmaDir, { recursive: true });
    fs.writeFileSync(path.join(annaDir, "profile.yaml"), "display_name: Anna\n");
    fs.writeFileSync(path.join(annaDir, "state.db"), "stub");
    fs.writeFileSync(path.join(emmaDir, "state.db"), "stub");
    setBotPrivateInPushStore("emma", true);

    let annaRows: WatchedDbMessageRow[] = [{ id: 10, role: "assistant", content: "old" }];
    let emmaRows: WatchedDbMessageRow[] = [{ id: 5, role: "assistant", content: "old" }];

    const dispatched: Array<{ title: string; body: string; bot?: string }> = [];
    const dispatchMock = vi.fn(async (payload: { title: string; body: string; bot?: string }) => {
      dispatched.push(payload);
      return { sent: 1, failed: 0, total: 1 };
    });

    const watcher = startHermesPushWatcher({
      hermesHome,
      pollIntervalMs: 60_000,
      queryDb: async (dbPath, sql) => {
        const isAnna = dbPath.includes("anna-coding");
        const rows = isAnna ? annaRows : emmaRows;
        if (sql.includes("MAX(id)")) {
          return [{ id: rows[rows.length - 1]?.id ?? 0, role: "system", content: "" }];
        }
        return rows.filter((r) => r.id > (isAnna ? 10 : 5));
      },
      dispatch: dispatchMock,
    });

    // Wait for initial startup seed
    await new Promise((r) => setTimeout(r, 20));
    expect(dispatched).toHaveLength(0);

    // Simulate new reply from Anna and Emma + touch DB mtime
    annaRows = [
      ...annaRows,
      { id: 11, role: "assistant", content: "Dein neues Bild ist fertig!\nMEDIA:/tmp/img.png", session_source: "gui" },
    ];
    emmaRows = [
      ...emmaRows,
      { id: 6, role: "assistant", content: "Private message", session_source: "gui" },
    ];
    const future = new Date(Date.now() + 5000);
    fs.utimesSync(path.join(annaDir, "state.db"), future, future);
    fs.utimesSync(path.join(emmaDir, "state.db"), future, future);

    // While user is backgrounded (default), Anna pushes and private Emma is blocked
    updateClientPushPresence(false);
    const count = await watcher.pollOnce();
    expect(count).toBe(1);
    expect(dispatched).toEqual([
      expect.objectContaining({
        title: "Anna",
        body: "Dein neues Bild ist fertig!",
        bot: "anna-coding",
      }),
    ]);

    // When user is actively looking at the app in the foreground, skip redundant push
    annaRows = [
      ...annaRows,
      { id: 12, role: "assistant", content: "Noch eine Nachricht", session_source: "gui" },
    ];
    const future2 = new Date(Date.now() + 10_000);
    fs.utimesSync(path.join(annaDir, "state.db"), future2, future2);
    updateClientPushPresence(true);
    const countFg = await watcher.pollOnce();
    expect(countFg).toBe(0);

    // Also verify manual send-push deduplication
    recordBotPushSent("anna-coding");
    annaRows = [
      ...annaRows,
      { id: 13, role: "assistant", content: "Dritte Nachricht", session_source: "gui" },
    ];
    const future3 = new Date(Date.now() + 15_000);
    fs.utimesSync(path.join(annaDir, "state.db"), future3, future3);
    updateClientPushPresence(false);
    const countDedup = await watcher.pollOnce();
    expect(countDedup).toBe(0);

    watcher.stop();
  });
});
